/** Every item on today's menu. */
export function getAllFoods(): FoodItem[] {
  return FOODS;
}

/** Items served at a given meal, in menu order. */
export function getFoodsByMeal(meal: Meal): FoodItem[] {
  return FOODS.filter((food) => food.meals.includes(meal));
}

/** One item by its slug, or `undefined` if there is no match. */
export function getFoodById(id: string): FoodItem | undefined {
  return FOODS.find((food) => food.id === id);
}
